// eggformat_spec.go —— F24「乙·单向派生」的子端面：**真源抽取 ＋ 生成器 ＋ 一致性门 ＋ 自检**。
//
// 真源（唯一机检）：core/cmd/zerg/zerg_egg_version.go 的两张表
// `zegIndexKeySpecs` / `zegEntryKeySpecs`。★ 本件**只取这两段表字面量的字节**（✗ 不取整文件）
// ⇒ 真源文件别处的注释 / 档表改动**不影响**派生指纹。
//
// 派生件：agent/internal/eggpkg/eggformat_gen.go（★ 由 `EggRenderDerived` 生成 · 走 dev edit 正门落盘）。
//
// 一致性门 `EggSpecGate` 三态：
//
//	① 派生件头记的真源 sha16 ⟷ 现读真源重算的 sha16（不符 ⇒ **真源改动而派生件未重生** ⇒ 点名真源）；
//	② 派生件全文 ⟷ 现读真源重生出的全文（不符 ⇒ **派生件被手改** ⇒ 点名派生件）；
//	③ 真源 / 派生件取不到 ⇒ **不给结论**（rc=2 · fail-closed）。
//
// ★ 硬线：本件**不 import** core 任何包（agent 与 core 是两个独立 module ⇒ 只按**路径 + 字节**读真源）。
// ★ 硬线：本件**不删** eggpkg 旧实现（`ReadIndex`/`validate`/`BuildPlan` 保留到 卵4（`-12`）定型）。
package eggpkg

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// EggSpecSourcePath / EggDerivedPath —— 真源件与派生件（相对仓根 · 与真源件里两张表的位置对齐）。
const (
	EggSpecSourcePath = "core/cmd/zerg/zerg_egg_version.go"
	EggDerivedPath    = "agent/internal/eggpkg/eggformat_gen.go"
)

// eggSpecTableVars —— 真源里被当作「唯一机检真源」的两张表（★ 顺序即指纹顺序）。
var eggSpecTableVars = []string{"zegIndexKeySpecs", "zegEntryKeySpecs"}

// eggSpec() —— 真源两张表合起来的花括号段字节（给对拍 / 报告用；不落盘）。
func eggSpecRegionOf(src []byte) ([]byte, error) {
	var buf bytes.Buffer
	for _, name := range eggSpecTableVars {
		lit, err := eggExtractTableLiteral(src, name)
		if err != nil {
			return nil, err
		}
		buf.Write(lit)
		buf.WriteByte('\n')
	}
	return buf.Bytes(), nil
}

// EggSpecSourceSHA —— 真源两张表的规格 sha256（前 16 位 hex）。取不到 / 抽不出 ⇒ 报错（fail-closed）。
func EggSpecSourceSHA(repoRoot string) (string, error) {
	src, err := os.ReadFile(filepath.Join(repoRoot, EggSpecSourcePath))
	if err != nil {
		return "", fmt.Errorf("真源取不到（%s）：%w", EggSpecSourcePath, err)
	}
	return eggSpecSourceSHAOf(src)
}

func eggSpecSourceSHAOf(src []byte) (string, error) {
	region, err := eggSpecRegionOf(src)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(region)
	return hex.EncodeToString(sum[:])[:16], nil
}

// eggExtractTableLiteral —— 从真源字节里取 `var <name> = []zegKeySpec{ … }` 的**花括号段字节**（含首尾
// `{`/`}`）。✗ 不引 Go 语法解析器（避免重依赖）：自写一个**尊重字符串 / 反引号 / 字符字面量**的花括号
// 配对扫描器 —— 表里的 `Why` 含反引号与中文，不跳过会把 `}` 配错。
func eggExtractTableLiteral(src []byte, name string) ([]byte, error) {
	marker := "var " + name + " = []zegKeySpec{"
	i := bytes.Index(src, []byte(marker))
	if i < 0 {
		return nil, fmt.Errorf("真源里找不到表 `%s`（锚串 %q）", name, marker)
	}
	open := i + len(marker) - 1 // 指向 '{'
	depth := 0
	inStr, inRaw, inRune := false, false, false
	for j := open; j < len(src); j++ {
		c := src[j]
		switch {
		case inRaw:
			if c == '`' {
				inRaw = false
			}
			continue
		case inStr:
			if c == '\\' {
				j++
				continue
			}
			if c == '"' {
				inStr = false
			}
			continue
		case inRune:
			if c == '\\' {
				j++
				continue
			}
			if c == '\'' {
				inRune = false
			}
			continue
		}
		switch c {
		case '`':
			inRaw = true
		case '"':
			inStr = true
		case '\'':
			inRune = true
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return src[open : j+1], nil
			}
		}
	}
	return nil, fmt.Errorf("真源表 `%s` 的花括号不配对（扫到文件末尾未闭合）", name)
}

// eggTransformLiteral —— 把真源表字面量转成派生件可用的形态：只换**面常量名**（类型名由渲染器写），
// `Key`/`Surface`/`Kind`/`Why` 字段与全部取值**逐字不变**（✗ 不改语义）。
func eggTransformLiteral(lit []byte) []byte {
	s := string(lit)
	s = strings.ReplaceAll(s, "zegSurfaceIncompat", "eggSurfaceIncompat")
	s = strings.ReplaceAll(s, "zegSurfaceCompat", "eggSurfaceCompat")
	return []byte(s)
}

// EggRenderDerived —— 由真源**唯一**渲染出派生件全文（确定性：同一真源 ⇒ 逐字节同）。
func EggRenderDerived(repoRoot string) ([]byte, error) {
	src, err := os.ReadFile(filepath.Join(repoRoot, EggSpecSourcePath))
	if err != nil {
		return nil, fmt.Errorf("真源取不到（%s）：%w", EggSpecSourcePath, err)
	}
	return eggRenderDerivedFromSource(src)
}

func eggRenderDerivedFromSource(src []byte) ([]byte, error) {
	sha16, err := eggSpecSourceSHAOf(src)
	if err != nil {
		return nil, err
	}
	idxLit, err := eggExtractTableLiteral(src, "zegIndexKeySpecs")
	if err != nil {
		return nil, err
	}
	entLit, err := eggExtractTableLiteral(src, "zegEntryKeySpecs")
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by zerg eggpkg spec generator (`eggspecgen --emit`); DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// 真源（唯一机检）：%s —— 两张表 zegIndexKeySpecs / zegEntryKeySpecs。\n", EggSpecSourcePath)
	fmt.Fprintf(&b, "// 真源规格 sha256（前16）: %s\n", sha16)
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// 一致性门：`eggspecgen --check`（EggSpecGate）—— 真源 sha 不符（未重生）或派生件被手改 ⇒ 判红点名。\n")
	fmt.Fprintf(&b, "package eggpkg\n\n")
	fmt.Fprintf(&b, "// eggGenSpecSHA —— 生成时真源两张表的规格 sha256（前 16 位 hex）。\n")
	fmt.Fprintf(&b, "const eggGenSpecSHA = %q\n\n", sha16)
	fmt.Fprintf(&b, "// eggGenIndexKeys —— 真源 `zegIndexKeySpecs` 的**单向派生**（子端索引键判据由此表驱动）。\n")
	fmt.Fprintf(&b, "var eggGenIndexKeys = []eggSpecKey%s\n\n", string(eggTransformLiteral(idxLit)))
	fmt.Fprintf(&b, "// eggGenEntryKeys —— 真源 `zegEntryKeySpecs` 的**单向派生**（子端段键判据由此表驱动）。\n")
	fmt.Fprintf(&b, "var eggGenEntryKeys = []eggSpecKey%s\n", string(eggTransformLiteral(entLit)))
	return b.Bytes(), nil
}

// ---- 一致性门（三态）------------------------------------------------------------------------

// 门的三态（★ 与命令面退码一致：0 绿 · 1 红 · 2 不给结论）。
const (
	EggSpecGateGreen     = 0
	EggSpecGateRed       = 1
	EggSpecGateNoVerdict = 2
)

// EggSpecGateResult —— 一次一致性门的结论。
type EggSpecGateResult struct {
	Status     int    `json:"status"`      // 0/1/2
	Message    string `json:"message"`     // 人面一行（点名件在里面）
	Named      string `json:"named"`       // 被点名的件（相对仓根）
	SourceSHA  string `json:"source_sha"`  // 现读真源重算的 sha16（取到时）
	DerivedSHA string `json:"derived_sha"` // 派生件头里记的 sha16（读到时）
}

// EggSpecGate —— 单向派生的一致性门。真源 / 派生件任一取不到 ⇒ 不给结论（✗ 不静默判绿）。
func EggSpecGate(repoRoot string) EggSpecGateResult {
	srcPath := filepath.Join(repoRoot, EggSpecSourcePath)
	derPath := filepath.Join(repoRoot, EggDerivedPath)

	src, err := os.ReadFile(srcPath)
	if err != nil {
		return EggSpecGateResult{Status: EggSpecGateNoVerdict, Named: EggSpecSourcePath,
			Message: fmt.Sprintf("真源取不到（%s）：%v —— 不给结论（rc=2）", EggSpecSourcePath, err)}
	}
	srcSHA, err := eggSpecSourceSHAOf(src)
	if err != nil {
		return EggSpecGateResult{Status: EggSpecGateNoVerdict, Named: EggSpecSourcePath,
			Message: fmt.Sprintf("真源两张表抽不出：%v —— 不给结论（rc=2）", err)}
	}
	want, err := eggRenderDerivedFromSource(src)
	if err != nil {
		return EggSpecGateResult{Status: EggSpecGateNoVerdict, Named: EggSpecSourcePath,
			Message: fmt.Sprintf("真源重生派生件失败：%v —— 不给结论（rc=2）", err)}
	}
	got, err := os.ReadFile(derPath)
	if err != nil {
		return EggSpecGateResult{Status: EggSpecGateNoVerdict, Named: EggDerivedPath, SourceSHA: srcSHA,
			Message: fmt.Sprintf("派生件取不到（%s）：%v —— 不给结论（rc=2）", EggDerivedPath, err)}
	}
	derSHA := eggDerivedRecordedSHA(got)
	res := EggSpecGateResult{SourceSHA: srcSHA, DerivedSHA: derSHA}
	// ① 派生件头记的 sha ⟷ 现读真源 sha（不符 ⇒ 真源改动而派生件未重生）。
	if derSHA != srcSHA {
		res.Status = EggSpecGateRed
		res.Named = EggSpecSourcePath
		res.Message = fmt.Sprintf("✗ 真源规格 sha16 不符：真源现读 %s ⟷ 派生件头记 %s —— 真源已改而派生件未重生（点名 %s）；跑 `eggspecgen --emit` 重生后走 dev edit 正门落盘",
			srcSHA, derSHA, EggSpecSourcePath)
		return res
	}
	// ② 派生件全文 ⟷ 真源重生全文（不符 ⇒ 派生件被手改）。
	if !bytes.Equal(got, want) {
		res.Status = EggSpecGateRed
		res.Named = EggDerivedPath
		res.Message = fmt.Sprintf("✗ 派生件与真源重生结果不符（手改或未重生）：%s 现读 %d 字节 ⟷ 重生 %d 字节（点名 %s）；✗ 不许手改派生件，重生后走 dev edit 正门落盘",
			EggDerivedPath, len(got), len(want), EggDerivedPath)
		return res
	}
	res.Status = EggSpecGateGreen
	res.Message = fmt.Sprintf("✓ 一致：真源 sha16 %s ⟷ 派生件头 %s；派生件与重生逐字节同（%d 字节）",
		srcSHA, derSHA, len(got))
	return res
}

// eggDerivedRecordedSHA —— 从派生件正文里取 `const eggGenSpecSHA = "…"` 记的那个 sha（取不到 ⇒ ""）。
func eggDerivedRecordedSHA(derived []byte) string {
	const marker = "const eggGenSpecSHA = "
	s := string(derived)
	i := strings.Index(s, marker)
	if i < 0 {
		return ""
	}
	rest := s[i+len(marker):]
	if len(rest) < 2 || rest[0] != '"' {
		return ""
	}
	end := strings.IndexByte(rest[1:], '"')
	if end < 0 {
		return ""
	}
	return rest[1 : 1+end]
}

// ---- 子端「表驱动」判据（判据表全部来自派生件 ⇒ 真源一改、重生即随动）--------------------------

// EggSurface / eggSpecKey —— 与真源 `zegKeySpec` 同形的键规格（✗ 不改语义）。
type EggSurface string

const (
	eggSurfaceIncompat EggSurface = "incompat"
	eggSurfaceCompat   EggSurface = "compat"
)

type eggSpecKey struct {
	Key     string
	Surface EggSurface
	Kind    string
	Why     string
}

func eggJSONKindOf(raw json.RawMessage) string {
	s := strings.TrimSpace(string(raw))
	if s == "" {
		return "empty"
	}
	switch s[0] {
	case '"':
		return "string"
	case '{':
		return "object"
	case '[':
		return "array"
	case 't', 'f':
		return "bool"
	case 'n':
		return "null"
	}
	return "number"
}

// EggAuditBySpec —— 子端**表驱动**判据（判据表＝派生件里的 `eggGenIndexKeys` / `eggGenEntryKeys`）：
//
//	① 不可变面必需键缺项 ⇒ 记一条（点名键）；
//	② 已知键 JSON 类型变了 ⇒ 记一条「同键换语义」（点名键）；
//	③ 未知顶层键 ⇒ 记一条「可加面登记」（照 OCI「MUST NOT error」）。
//
// ★ 判据**全来自生成物** ⇒ 真源改、重生即随动（✗ 无手写的第二份判据表）。
func EggAuditBySpec(indexJSON []byte) ([]string, error) {
	var top map[string]json.RawMessage
	if err := json.Unmarshal(indexJSON, &top); err != nil {
		return nil, fmt.Errorf("索引 JSON 不可解析：%w", err)
	}
	var out []string
	known := make(map[string]bool, len(eggGenIndexKeys))
	for _, spec := range eggGenIndexKeys {
		known[spec.Key] = true
		raw, has := top[spec.Key]
		if !has {
			if spec.Surface == eggSurfaceIncompat {
				out = append(out, fmt.Sprintf("缺不可变面必需键 %q", spec.Key))
			}
			continue
		}
		if k := eggJSONKindOf(raw); k != spec.Kind {
			out = append(out, fmt.Sprintf("同键换语义：%q 由 %s 变成 %s", spec.Key, spec.Kind, k))
		}
	}
	for k := range top {
		if !known[k] {
			out = append(out, fmt.Sprintf("可加面未知键 %q（忽略并登记）", k))
		}
	}
	sort.Strings(out)
	return out, nil
}

