// EggSpecSelfTestLastLine —— 自检**末行**（逐字对拍用；★ 不含任何运行期变量 ⇒ 每次逐字同）。
const EggSpecSelfTestLastLine = "self-test（F24 卵格式单向派生 · 一致性门）通过（4 态 ＋ 2 负控）：" +
	"① 一致态 ⇒ 绿 · " +
	"② 真源改动未重生 ⇒ 红且点名 core/cmd/zerg/zerg_egg_version.go · " +
	"③ 派生件手改 ⇒ 红且点名 agent/internal/eggpkg/eggformat_gen.go · " +
	"④ 真源取不到 ⇒ rc=2 不给结论 · " +
	"负控：sha-only 检查器在③上仍绿（＝正文比对有独立牙）· ②重生成后转绿"

// EggSpecSelfTest —— 四态亲测 ＋ 两枚负控（真造合成仓 · 不碰真仓）。
func EggSpecSelfTest(stdout, stderr io.Writer) int {
	t, err := os.MkdirTemp("", "zerg-eggspec-selftest")
	if err != nil {
		fmt.Fprintf(stderr, "eggspec: %v\n", err)
		return EggSpecGateRed
	}
	defer os.RemoveAll(t) // 自回收（TMPDIR 前后 delta=0）

	// mkRoot —— 造一个合成仓：写真源 ＋（按现真源）重生派生件。
	mkRoot := func(name string, src []byte) (string, error) {
		root := filepath.Join(t, name)
		if err := os.MkdirAll(filepath.Join(root, filepath.Dir(EggSpecSourcePath)), 0o755); err != nil {
			return "", err
		}
		if err := os.MkdirAll(filepath.Join(root, filepath.Dir(EggDerivedPath)), 0o755); err != nil {
			return "", err
		}
		if err := os.WriteFile(filepath.Join(root, EggSpecSourcePath), src, 0o644); err != nil {
			return "", err
		}
		der, derr := eggRenderDerivedFromSource(src)
		if derr != nil {
			return "", derr
		}
		if err := os.WriteFile(filepath.Join(root, EggDerivedPath), der, 0o644); err != nil {
			return "", err
		}
		return root, nil
	}
	base := []byte(fmt.Sprintf(eggSpecSynthTemplate, "\t"))
	changed := []byte(fmt.Sprintf(eggSpecSynthTemplate, "\t{Key: \"min_readable\", Surface: zegSurfaceCompat, Kind: \"number\", Why: \"synth\"},\n"))

	// 负控用的**弱化检查器**（只比头里的 sha · ✗ 不比正文）：证明正文比对有独立牙。
	shaOnlyGreen := func(root string) bool {
		src, rerr := os.ReadFile(filepath.Join(root, EggSpecSourcePath))
		if rerr != nil {
			return false
		}
		want, werr := eggSpecSourceSHAOf(src)
		if werr != nil {
			return false
		}
		got, gerr := os.ReadFile(filepath.Join(root, EggDerivedPath))
		if gerr != nil {
			return false
		}
		return eggDerivedRecordedSHA(got) == want
	}

	// ---- 态①：一致态 ⇒ 绿 ----
	root1, err := mkRoot("s1", base)
	if err != nil {
		return eggSpecSelfFail(stderr, err)
	}
	if g := EggSpecGate(root1); g.Status != EggSpecGateGreen {
		return eggSpecSelfFail(stderr, fmt.Errorf("态① 一致态竟非绿：status=%d · %s", g.Status, g.Message))
	}

	// ---- 态②：真源改动而派生件未重生 ⇒ 必红且点名真源 ----
	root2, err := mkRoot("s2", base)
	if err != nil {
		return eggSpecSelfFail(stderr, err)
	}
	if err := os.WriteFile(filepath.Join(root2, EggSpecSourcePath), changed, 0o644); err != nil {
		return eggSpecSelfFail(stderr, err)
	}
	g2 := EggSpecGate(root2)
	if g2.Status != EggSpecGateRed || g2.Named != EggSpecSourcePath {
		return eggSpecSelfFail(stderr, fmt.Errorf("态② 真源改了未重生竟非「红且点名真源」：status=%d named=%q · %s", g2.Status, g2.Named, g2.Message))
	}
	// 负控②：把该改后真源**重生一次** ⇒ 门必须转绿（证明上面那条红是「未重生」而非门本身永红）。
	der2, rerr := eggRenderDerivedFromSource(changed)
	if rerr != nil {
		return eggSpecSelfFail(stderr, rerr)
	}
	if err := os.WriteFile(filepath.Join(root2, EggDerivedPath), der2, 0o644); err != nil {
		return eggSpecSelfFail(stderr, err)
	}
	if g := EggSpecGate(root2); g.Status != EggSpecGateGreen {
		return eggSpecSelfFail(stderr, fmt.Errorf("负控② 重生后应转绿：status=%d · %s", g.Status, g.Message))
	}

	// ---- 态③：派生件被手改（头 sha 未动）⇒ 必红且点名派生件 ----
	root3, err := mkRoot("s3", base)
	if err != nil {
		return eggSpecSelfFail(stderr, err)
	}
	der3, rerr := os.ReadFile(filepath.Join(root3, EggDerivedPath))
	if rerr != nil {
		return eggSpecSelfFail(stderr, rerr)
	}
	tampered := bytes.Replace(der3, []byte(`Why: "synth"`), []byte(`Why: "tampered"`), 1)
	if bytes.Equal(tampered, der3) {
		return eggSpecSelfFail(stderr, fmt.Errorf("态③ 夹具坏：派生件里找不到可改处"))
	}
	if err := os.WriteFile(filepath.Join(root3, EggDerivedPath), tampered, 0o644); err != nil {
		return eggSpecSelfFail(stderr, err)
	}
	g3 := EggSpecGate(root3)
	if g3.Status != EggSpecGateRed || g3.Named != EggDerivedPath {
		return eggSpecSelfFail(stderr, fmt.Errorf("态③ 派生件手改竟非「红且点名派生件」：status=%d named=%q · %s", g3.Status, g3.Named, g3.Message))
	}
	// 负控①：同一态③ 走**只比 sha** 的弱化检查器 ⇒ 必须**绿**（＝正文比对才有那枚独立的牙）。
	if !shaOnlyGreen(root3) {
		return eggSpecSelfFail(stderr, fmt.Errorf("负控① 前提不成立：只比 sha 的检查器在态③上竟也红（那正文比对就无独立牙了）"))
	}

	// ---- 态④：真源取不到 ⇒ rc=2（不给结论）----
	root4, err := mkRoot("s4", base)
	if err != nil {
		return eggSpecSelfFail(stderr, err)
	}
	if err := os.Remove(filepath.Join(root4, EggSpecSourcePath)); err != nil {
		return eggSpecSelfFail(stderr, err)
	}
	if g := EggSpecGate(root4); g.Status != EggSpecGateNoVerdict {
		return eggSpecSelfFail(stderr, fmt.Errorf("态④ 真源取不到竟给了结论：status=%d · %s", g.Status, g.Message))
	}

	fmt.Fprintln(stdout, EggSpecSelfTestLastLine)
	return EggSpecGateGreen
}

func eggSpecSelfFail(stderr io.Writer, err error) int {
	fmt.Fprintf(stderr, "eggspec: 自检失败：%v\n", err)
	return EggSpecGateRed
}
