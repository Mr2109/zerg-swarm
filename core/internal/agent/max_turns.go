// max_turns.go — 轮数上限的**唯一真源**（§二十一 已红第 12 条「`max_turns` 三处不等（100 / 30 / 20）」·
// 批 C 的 T-34）。
//
// 病灶（照已红原话）：**同一条上限三个真源** —— 命令行默认（100）· 主循环兜底（30）· 子任务配额（20），
// 加上 `loop.go` 里还有第四处兜底（100）。四个数字各有各的历史，谁改一处另外三处不会跟着动，
// 而且**没有任何东西会报红**：现象只是「同一条命令在不同入口下跑到不同的轮数」。
//
// 口径（三条，逐条可机检）：
//
//	① **主上限只有一个数**：命令行 `-max-turns` 的默认值、`Config.MaxTurns == 0` 的兜底、
//	   `newLoop` 收到非正数时的兜底 —— 三处**全部**取 `DefaultMaxTurns`，不许再出现字面量。
//	② **子任务配额从主上限派生**（`SubAgentMaxTurns`）：子任务**绝不许比主任务宽** ——
//	   派生写法让这条关系是构造上的，而不是靠两个数字碰巧一个比另一个小。
//	③ **子任务的默认值不许回到同一个数**：`DefaultMaxTurns > SubAgentMaxTurns` 是一条断言
//	   （见 `max_turns_test.go`）—— 有人把子配额调成 100，那条测试当场红。
package agent

const (
	// DefaultMaxTurns —— 主循环轮数上限（唯一真源）。v2.5 起是 100：
	// v2.5 之前是 30，研究类任务（要 100+ 轮）会被腰斩；自主停止（模型自己说完成）才是主路，
	// 这个数只是**安全兜底**。
	DefaultMaxTurns = 100

	// SubAgentMaxTurns —— 子任务（`spawn_agent`）每层配额。**从主上限派生**：
	// 口径是「子任务不许比主任务宽」，所以它是 DefaultMaxTurns 的 1/5（= 20，与历史值一致）。
	SubAgentMaxTurns = DefaultMaxTurns / 5
)
