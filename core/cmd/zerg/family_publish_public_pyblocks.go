// 坏串 ⇒ 返回 ""（调用方 fail-closed，✗ 不静默拿空脚本喂 python3）。
func ppPyDecode(s string) string {
	b, err := base64.RawURLEncoding.DecodeString(s)
	if err != nil {
		return ""
	}
	return string(b)
}

